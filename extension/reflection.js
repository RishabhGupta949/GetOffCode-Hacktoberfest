const API_BASE = "https://touchgrass-api-vat6.onrender.com/api/v1";

async function sendMsg(msg) {
  return new Promise(resolve => chrome.runtime.sendMessage(msg, resolve));
}

function showError(msg) {
  const existing = document.querySelector(".toast-error");
  if (existing) existing.remove();
  const el = document.createElement("div");
  el.className = "toast-error";
  el.textContent = msg;
  el.style.cssText = `
    position: fixed; bottom: 24px; left: 50%; transform: translateX(-50%);
    background: #ef4444; color: #fff; padding: 12px 24px; border-radius: 8px;
    box-shadow: 0 10px 25px rgba(0,0,0,0.2); z-index: 10000;
    animation: slideUp 0.3s ease;
  `;
  const style = document.createElement("style");
  style.textContent = `@keyframes slideUp { from { opacity: 0; transform: translateX(-50%) translateY(10px); } to { opacity: 1; transform: translateX(-50%) translateY(0); } }`;
  document.head.appendChild(style);
  document.body.appendChild(el);
  setTimeout(() => el.remove(), 5000);
}

function setChoiceState(choice) {
  document.querySelectorAll(".choice-btn").forEach(btn => {
    const isSelected = btn.dataset.choice === choice;
    btn.style.borderColor = isSelected ? "#22c55e" : "#e2e8f0";
    btn.style.background = isSelected ? "#f0fdf4" : "#fff";
  });
}

async function handleChoice(choice) {
  setChoiceState(choice);

  try {
    const resp = await sendMsg({ type: "REFLECT", choice });
    if (!resp || resp.error) {
      showError(resp?.error || "Failed to record reflection");
      return;
    }

    if (resp.state === "USER_HAS_IDEA") {
      // YES or MAYBE - encourage trying own idea, resume work
      document.querySelector(".choices").classList.add("hidden");
      document.querySelector(".hypothesis-section").classList.add("hidden");
      document.querySelector(".header h1").textContent = choice === "idea" ? "Great! Try your idea." : "Good. Keep thinking.";
      document.querySelector(".header .subtitle").textContent = "The best solution is often your own.";
      document.getElementById("backLink").style.display = "block";
    } else if (resp.state === "AI_ASSISTANCE_ALLOWED") {
      // NO - show "May I suggest?" and request hypothesis
      document.querySelector(".choices").classList.add("hidden");
      document.querySelector(".header h1").textContent = "May I suggest one possibility?";
      document.querySelector(".header .subtitle").textContent = "A tentative hypothesis, not a guaranteed fix.";
      await requestHypothesis();
    }
  } catch (e) {
    showError("Backend unreachable. Is the server running?");
  }
}

async function requestHypothesis() {
  const section = document.getElementById("hypothesisSection");
  const textEl = document.getElementById("hypText");
  const sourceEl = document.getElementById("hypSource");

  textEl.textContent = "Thinking...";
  section.classList.add("visible");

  try {
    const resp = await sendMsg({ type: "REQUEST_HYPOTHESIS" });
    if (resp?.hypothesis) {
      currentHypothesisId = resp.hypothesis_id;
      textEl.textContent = resp.hypothesis;
      const srcLabels = { ai: "Generated by AI", cache: "From similar past problems", fallback: "General debugging pattern" };
      sourceEl.textContent = srcLabels[resp.source] || resp.source;
    } else {
      textEl.textContent = "Couldn't generate a suggestion right now. Try again later?";
      sourceEl.textContent = "";
    }
  } catch (e) {
    textEl.textContent = "Failed to get suggestion. Check backend connection.";
    sourceEl.textContent = "";
  }
}

async function handleFeedback(outcome) {
  document.querySelectorAll(".feedback-btn").forEach(btn => {
    btn.classList.toggle("selected", btn.dataset.outcome === outcome);
    btn.disabled = true;
  });

  try {
    const resp = await sendMsg({ type: "SUBMIT_FEEDBACK", hypothesis_id: currentHypothesisId, outcome });
    if (resp?.state === "WORKING") {
      // Success - close reflection, back to popup/work
      document.getElementById("hypText").textContent = "Thanks! Your feedback helps future suggestions.";
      document.querySelector(".feedback").style.display = "none";
      setTimeout(() => window.close(), 1500);
    } else {
      showError(resp?.error || "Failed to save feedback");
      document.querySelectorAll(".feedback-btn").forEach(btn => btn.disabled = false);
    }
  } catch (e) {
    showError("Backend unreachable");
    document.querySelectorAll(".feedback-btn").forEach(btn => btn.disabled = false);
  }
}

